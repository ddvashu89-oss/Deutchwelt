    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,
    UNIQUE INDEX `TeacherApplication_teacherUserId_key`(`teacherUserId`),
    INDEX `TeacherApplication_status_createdAt_idx`(`status`, `createdAt`),
    INDEX `TeacherApplication_email_status_idx`(`email`, `status`),
